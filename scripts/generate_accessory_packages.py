        # Keep every roller crown on the 890 mm deck plane as fine pitches reduce diameter.
        append_z_cylinder(roller_vertices, roller_indices, x,
                          890.0 - default_roller_radius_mm,
                          -305.0, 305.0, default_roller_radius_mm)
