        mesh_node("Adjustable feet", "meshes/feet.meshbin", [0.08, 0.09, 0.10, 1.0]),
        mesh_node("Steel rollers", "meshes/rollers.meshbin", [0.68, 0.71, 0.73, 1.0]),
