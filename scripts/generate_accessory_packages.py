#!/usr/bin/env python3
"""Generate the built-in conveyor, table, and reusable workpiece accessory packages."""

from __future__ import annotations

import json
import math
from pathlib import Path

from pkglib import LIBRARY_PACKAGES, LIBRARY_SOURCES
from pkglib.archive import write_zip
from pkglib.geom import append_box, append_perforated_cell, append_z_cylinder
from pkglib.meshbin import write_meshbin
from pkglib.nodes import mesh_node, root_node, transform_node


def write_package(package_dir: Path, archive_path: Path, manifest: dict,
                  meshes: dict[str, tuple[list[float], list[int]]]) -> None:
    package_dir.mkdir(parents=True, exist_ok=True)
    for relative_path, (vertices, indices) in meshes.items():
        write_meshbin(package_dir / relative_path, vertices, indices)
    (package_dir / "accessory.json").write_text(json.dumps(manifest, indent=2) + "\n",
                                                encoding="utf-8")
    # Zip only the named members: several packages share one mesh dict, and a stale file in the
    # package directory must not ride along.
    write_zip(package_dir, archive_path, members=["accessory.json", *sorted(meshes)])


