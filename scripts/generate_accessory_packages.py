        for z in (-280.0, 280.0):
            append_box(steel_vertices, steel_indices, (x, 390.0, z), (60.0, 760.0, 60.0))
            append_box(dark_vertices, dark_indices, (x, 5.0, z), (130.0, 10.0, 130.0))
