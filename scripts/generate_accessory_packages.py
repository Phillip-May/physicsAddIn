def generate_ar4_table() -> None:
    frame_vertices: list[float] = []
    frame_indices: list[int] = []
    top_vertices: list[float] = []
    top_indices: list[int] = []
    foot_vertices: list[float] = []
    foot_indices: list[int] = []

    for x in (-330.0, 330.0):
        for z in (-330.0, 330.0):
            append_box(frame_vertices, frame_indices, (x, 390.0, z), (60.0, 760.0, 60.0))
            append_box(foot_vertices, foot_indices, (x, 5.0, z), (120.0, 10.0, 120.0))
    for y in (120.0, 690.0):
        for z in (-330.0, 330.0):
            append_box(frame_vertices, frame_indices, (0.0, y, z), (720.0, 45.0, 45.0))
        for x in (-330.0, 330.0):
            append_box(frame_vertices, frame_indices, (x, y, 0.0), (45.0, 45.0, 720.0))

    # Forty-nine true through holes in a 7x7, 100 mm-pitch steel plate.
    for x in range(-300, 301, 100):
        for z in range(-300, 301, 100):
            append_perforated_cell(top_vertices, top_indices, float(x), float(z),
                                   800.0, 820.0, 100.0, 7.0)
    append_box(top_vertices, top_indices, (-375.0, 810.0, 0.0), (50.0, 20.0, 800.0))
    append_box(top_vertices, top_indices, (375.0, 810.0, 0.0), (50.0, 20.0, 800.0))
    append_box(top_vertices, top_indices, (0.0, 810.0, -375.0), (700.0, 20.0, 50.0))
    append_box(top_vertices, top_indices, (0.0, 810.0, 375.0), (700.0, 20.0, 50.0))

    source_holes = {
        "comment": ("Four virtual floor mounting centers at the AR4 table foot-plate centers. "
                    "Generated by scripts/generate_accessory_packages.py."),
        "placementSource": True,
        "grids": [{
            "originMm": [-330.0, 0.0, -330.0],
            "uStepMm": [660.0, 0.0, 0.0],
            "vStepMm": [0.0, 0.0, 660.0],
            "uCount": 2,
            "vCount": 2,
        }],
    }
    top_holes = {
        "comment": ("Seven by seven M8-clearance through-hole pattern on 100 mm pitch. The pitch "
                    "matches the AR4 external 100 by 100 mm base mounting pattern. Generated by "
                    "scripts/generate_accessory_packages.py."),
        "grids": [{
            "originMm": [-300.0, 820.0, -300.0],
            "uStepMm": [100.0, 0.0, 0.0],
            "vStepMm": [0.0, 0.0, 100.0],
            "uCount": 7,
            "vCount": 7,
        }],
    }
    manifest = root_node("AR4 Table — 100 mm pitch", [
        mesh_node("Welded frame", "meshes/frame.meshbin", [0.25, 0.28, 0.31, 1.0]),
        mesh_node("Floor plates", "meshes/feet.meshbin", [0.10, 0.11, 0.12, 1.0]),
        mesh_node("100 mm pitch perforated steel top", "meshes/top.meshbin",
                  [0.70, 0.73, 0.75, 1.0], top_holes),
    ], source_holes, {
        "generator": "ar4_table",
        "widthMm": 800.0,
        "lengthMm": 800.0,
        "heightMm": 820.0,
        "holePitchMm": 100.0,
    })
    write_package(LIBRARY_SOURCES / "ar4_table_100mm_pitch",
                  LIBRARY_PACKAGES / "ar4_table_100mm_pitch.zip", manifest, {
                      "meshes/frame.meshbin": (frame_vertices, frame_indices),
                      "meshes/feet.meshbin": (foot_vertices, foot_indices),
                      "meshes/top.meshbin": (top_vertices, top_indices),
                  })


def generate_box_workpiece() -> None:
    """A station-owned prototype that spawners clone; centered for visual/physics agreement."""
    vertices: list[float] = []
    indices: list[int] = []
    append_box(vertices, indices, (0.0, 0.0, 0.0), (120.0, 100.0, 120.0))
    placement_holes = {
        "comment": "Four virtual bottom-corner placement centers for the reusable box workpiece.",
        "placementSource": True,
        "grids": [{
            "originMm": [-50.0, -50.0, -50.0],
            "uStepMm": [100.0, 0.0, 0.0],
            "vStepMm": [0.0, 0.0, 100.0],
            "uCount": 2,
            "vCount": 2,
        }],
    }
    manifest = root_node("Box workpiece", [
        mesh_node("Box model", "meshes/box.meshbin", [0.925, 0.541, 0.165, 1.0]),
    ], placement_holes)
    write_package(LIBRARY_SOURCES / "box_workpiece",
                  LIBRARY_PACKAGES / "box_workpiece.zip", manifest, {
                      "meshes/box.meshbin": (vertices, indices),
                  })


